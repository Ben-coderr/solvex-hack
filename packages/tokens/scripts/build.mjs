// Emits dist/tokens.css (Tailwind v4 @theme + dark/light variables) and dist/theme.ts (React Native).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens as t } from './lib.mjs';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
mkdirSync(dist, { recursive: true });

const mode = (m) => Object.entries(t.color[m]).map(([k, v]) => `  --najda-${k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}: ${v};`).join('\n');
const css = `/* GENERATED by packages/tokens — do not edit by hand */
@theme {
${Object.entries(t.color.brand).map(([k, v]) => `  --color-brand-${k}: ${v};`).join('\n')}
${Object.entries(t.color.triage).map(([k, v]) => `  --color-triage-${k.toLowerCase()}: ${v};`).join('\n')}
${Object.entries(t.color.onTriage).map(([k, v]) => `  --color-on-triage-${k.toLowerCase()}: ${v};`).join('\n')}
  --font-ui: "${t.font.ui}", system-ui, sans-serif;
  --font-mono: "${t.font.mono}", ui-monospace, monospace;
  --font-display: "${t.font.display}", "${t.font.ui}", sans-serif;
${Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join('\n')}
}
:root, [data-theme="light"] {
${mode('light')}
}
[data-theme="dark"] {
${mode('dark')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${mode('dark').replace(/^/gm, '  ')}
  }
}
`;
writeFileSync(join(dist, 'tokens.css'), css);

const ts = `// GENERATED by packages/tokens — do not edit by hand
export const tokens = ${JSON.stringify(t, null, 2)} as const;
export type ThemeMode = 'dark' | 'light';
export const triageBands = ['R', 'O', 'Y', 'G', 'U'] as const;
export type TriageBand = (typeof triageBands)[number];
`;
writeFileSync(join(dist, 'theme.ts'), ts);
console.log('tokens built:', dist);

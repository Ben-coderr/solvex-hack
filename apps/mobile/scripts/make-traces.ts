/**
 * Writes the SYNTHETIC replay traces: data/traces/<name>.csv (the library, C's folder) and
 * src/replay/bundled-traces.ts (the same CSV text, bundled into the app for the stage replay).
 * Deterministic: re-running it produces byte-identical files.  Usage: pnpm --filter mobile traces
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { makeTrace, TRACE_NAMES } from '../src/detector/synth';
import { toCsv } from '../src/detector/trace';

const dataDir = new URL('../../../data/traces/', import.meta.url);
mkdirSync(dataDir, { recursive: true });

const bundled: string[] = [];
for (const name of TRACE_NAMES) {
  const csv = toCsv(makeTrace(name));
  writeFileSync(new URL(`${name}.csv`, dataDir), csv);
  bundled.push(`  ${name}: ${JSON.stringify(csv)},`);
  console.log(`data/traces/${name}.csv  ${csv.split('\n').length - 2} samples`);
}

writeFileSync(
  new URL('../src/replay/bundled-traces.ts', import.meta.url),
  `// GENERATED by scripts/make-traces.ts. Do not edit. SYNTHETIC traces (see data/traces/README.md).\n` +
    `import type { TraceName } from '../detector/synth';\n\n` +
    `export const BUNDLED_TRACES: Record<TraceName, string> = {\n${bundled.join('\n')}\n};\n`,
);
console.log('src/replay/bundled-traces.ts');

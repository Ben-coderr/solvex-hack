/**
 * Copies the replay traces the app ships VERBATIM from packages/detector/traces (CSV text + manifest metadata) into
 * src/replay/bundled-traces.ts. It never generates or edits a trace: regenerate them in the package
 * (`pnpm --filter @sellekni/detector traces`), then run this.  Usage: pnpm --filter mobile traces
 * test/replay.test.ts fails if the bundle drifts from the package files.
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** docs/17 §1: the two demo crashes, the two negatives shown on stage, two more traps, and the simulated BOX. */
export const SHIPPED = [
  'frontal_45_r16', 'rollover_71_r16', 'pothole_then_stop_r16', 'phone_drop_r16',
  'speed_bump_r16', 'hard_brake_r16', 'frontal_45_r200',
] as const;

interface ManifestEntry { file: string; scenario: string; rangeG: number; expect: 'alert' | 'no-alert'; note: string; label: string }

const dir = new URL('../../../packages/detector/traces/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('manifest.json', dir), 'utf8')) as ManifestEntry[];

const rows = SHIPPED.map((name) => {
  const m = manifest.find((e) => e.file === `${name}.csv`);
  if (!m) throw new Error(`${name}.csv is not in packages/detector/traces/manifest.json`);
  const csv = readFileSync(new URL(m.file, dir), 'utf8');
  const meta = { scenario: m.scenario, rangeG: m.rangeG, expect: m.expect, box: m.label.includes('BOX'), note: m.note };
  return `  ${name}: ${JSON.stringify(meta).slice(0, -1)}, "csv": ${JSON.stringify(csv)} },`;
});

writeFileSync(
  new URL('../src/replay/bundled-traces.ts', import.meta.url),
  `// GENERATED by scripts/bundle-traces.ts from packages/detector/traces. Do not edit. SYNTHETIC traces.\n` +
    `export const BUNDLED_TRACES = {\n${rows.join('\n')}\n} as const;\n\n` +
    `export type TraceName = keyof typeof BUNDLED_TRACES;\n` +
    `export const TRACE_NAMES = Object.keys(BUNDLED_TRACES) as TraceName[];\n`,
);
console.log(`src/replay/bundled-traces.ts  ${SHIPPED.length} traces`);

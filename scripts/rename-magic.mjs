#!/usr/bin/env node
// Rename the DZ-MSD wire magic (e.g. SLK1 -> SELK1) everywhere, recomputing every hard-coded CRC.
//
//   node scripts/rename-magic.mjs SLK1            # DRY RUN: lists what would change
//   node scripts/rename-magic.mjs SLK1 --write    # apply, regenerate golden vectors, run `pnpm check`
//
// Why a script: the CRC-8 covers the magic, so changing it invalidates every full packet that is
// written as a literal in tests, docs, fixtures and app code. Replacing the text by hand breaks the
// contract silently. This follows the sellekni-protocol procedure: change source -> change the
// independent Python implementation -> regenerate vectors -> review the diff -> pnpm check.
//
// Run it on a clean git branch. Review `git diff` before committing. Never edit vectors by hand.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { execSync } from 'node:child_process';

const args = process.argv.slice(2);
const NEW = args.find((a) => !a.startsWith('--'));
const WRITE = args.includes('--write');
const ROOT = process.cwd();
if (!NEW || !/^[A-Z]{2,8}[0-9]$/.test(NEW)) {
  console.error('usage: node scripts/rename-magic.mjs <NEWMAGIC> [--write]   (2-8 capital letters + one version digit, e.g. SLK1)');
  process.exit(2);
}

const dz = readFileSync(join(ROOT, 'packages/shared/src/dzmsd.ts'), 'utf8');
const OLD = /export const MAGIC = '([A-Z0-9]+)'/.exec(dz)?.[1];
if (!OLD) { console.error('cannot find MAGIC in packages/shared/src/dzmsd.ts'); process.exit(2); }
if (OLD === NEW) { console.log(`magic is already ${NEW}`); process.exit(0); }
const delta = NEW.length - OLD.length;

// CRC-8/SMBUS (poly 0x07, init 0, no reflection) — same as packages/shared/src/crc8.ts
function crc8Hex(s) {
  let c = 0;
  for (const ch of s) {
    c ^= ch.charCodeAt(0);
    for (let i = 0; i < 8; i++) c = c & 0x80 ? ((c << 1) ^ 0x07) & 0xff : (c << 1) & 0xff;
  }
  return c.toString(16).toUpperCase().padStart(2, '0');
}

const SKIP_DIRS = new Set(['node_modules', '.git', '.next', '.expo', 'dist', 'build', 'android', 'ios', 'coverage', '.turbo']);
const TEXT_EXT = new Set(['.ts', '.tsx', '.js', '.mjs', '.cjs', '.py', '.json', '.md', '.sql', '.sh', '.yml', '.yaml', '.txt', '.csv']);
const SKIP_FILES = new Set(['pnpm-lock.yaml', 'package-lock.json', '12-DECISIONS-REBRAND-OBD-IOT.md']);

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) yield* walk(p);
    else if (TEXT_EXT.has(extname(name)) && !SKIP_FILES.has(name) && name !== 'rename-magic.mjs') yield p;
  }
}

// golden vectors are REGENERATED by `pnpm vectors`, never patched by regex
const isVector = (rel) => rel.includes('test-vectors/');

// a full packet literal:  OLD <tokens without quotes/newlines> #XX
const FULL = new RegExp(`${OLD}((?: [^'"\\\`\\n\\\\#]+?)) #([0-9A-Fa-f]{2})(?![0-9A-Za-z])`, 'g');

// Lengths quoted in tests/docs ("93 chars", "93/160", "(67 spare)", WIRE1.length, 93 …) move by `delta`.
// Old numbers come from the spec examples themselves, so this stays correct if they ever change.
const testSrc = readFileSync(join(ROOT, 'packages/shared/test/dzmsd.test.ts'), 'utf8');
const oldW1 = new RegExp(`const WIRE1 = '(${OLD}[^']+)'`).exec(testSrc)?.[1];
const oldW2 = new RegExp(`const WIRE2 = '(${OLD}[^']+)'`).exec(testSrc)?.[1];
const worstDoc = /absolute worst case = \*{0,2}(\d+)/.exec(readFileSync(join(ROOT, 'docs/05-PROTOCOL-SCORING-RANKING.md'), 'utf8'))?.[1];
const LEN_MAP = new Map();
for (const L of [oldW1?.length, oldW2?.length, worstDoc && Number(worstDoc)].filter(Boolean)) {
  LEN_MAP.set(String(L), String(L + delta));          // the length itself
  LEN_MAP.set(String(160 - L), String(160 - L - delta)); // the "spare" figure
}
const LEN_LINE = /(chars|characters|\/160|\.length|spare|worst case)/;
function fixLengths(text) {
  if (delta === 0 || LEN_MAP.size === 0) return text;
  return text
    .split('\n')
    .map((line) => (LEN_LINE.test(line) ? line.replace(/\b\d{2,3}\b/g, (d) => LEN_MAP.get(d) ?? d) : line))
    .join('\n');
}

function rewrite(text) {
  let n = 0;
  let out = text.replace(FULL, (_m, rest) => {
    n++;
    return `${NEW}${rest} #${crc8Hex(NEW + rest)}`;
  });
  // remaining occurrences (prefix-only strings, startsWith checks, "OLD" + "U" crew update, titles)
  const before = out;
  out = out.split(OLD).join(NEW);
  if (out !== before) n++;
  return { out, n };
}

const changed = [];
for (const file of walk(ROOT)) {
  const rel = relative(ROOT, file);
  if (isVector(rel)) continue;
  const text = readFileSync(file, 'utf8');
  // lines containing "keep-magic" (e.g. historical quotes of the old plan) are never touched
  const kept = [];
  const masked = text.split('\n').map((l, i) => (l.includes('keep-magic') ? (kept.push([i, l]), `\u0000KEEP${i}\u0000`) : l)).join('\n');
  let out = masked;
  let n = 0;
  if (masked.includes(OLD)) ({ out, n } = rewrite(masked));
  if (/^(docs\/|packages\/shared\/test\/|DEVELOPMENT\.md)/.test(rel)) out = fixLengths(out);
  for (const [i, l] of kept) out = out.replace(`\u0000KEEP${i}\u0000`, () => l);
  if (out !== text) {
    changed.push({ rel, n });
    if (WRITE) writeFileSync(file, out);
  }
}

// test titles that quote the literal lengths/CRCs of the two spec examples
const titleFix = (rel, from, to) => {
  const p = join(ROOT, rel);
  try {
    const t = readFileSync(p, 'utf8');
    if (t.includes(from) && WRITE) writeFileSync(p, t.replace(from, to));
  } catch { /* file may not exist in a trimmed repo */ }
};

console.log(`${WRITE ? 'APPLIED' : 'DRY RUN'}: ${OLD} -> ${NEW}  (packet length changes by ${delta >= 0 ? '+' : ''}${delta} chars)`);
for (const c of changed) console.log(`  ${c.rel}`);
if (!changed.length) console.log('  (nothing to change)');

if (!WRITE) {
  console.log('\nRe-run with --write to apply, regenerate golden vectors and run `pnpm check`.');
  process.exit(0);
}

// the canonical-example test title embeds old CRCs/lengths; recompute them from the new packets
const w1 = readFileSync(join(ROOT, 'packages/shared/test/dzmsd.test.ts'), 'utf8').match(/const WIRE1 = '([^']+)'/)?.[1];
const w2 = readFileSync(join(ROOT, 'packages/shared/test/dzmsd.test.ts'), 'utf8').match(/const WIRE2 = '([^']+)'/)?.[1];
if (w1 && w2) {
  const t = readFileSync(join(ROOT, 'packages/shared/test/dzmsd.test.ts'), 'utf8');
  const fixed = t.replace(/\(CRC \\?#[0-9A-F]{2} and \\?#[0-9A-F]{2}, \d+ and \d+ chars\)/, `(CRC #${w1.slice(-2)} and #${w2.slice(-2)}, ${w1.length} and ${w2.length} chars)`);
  if (fixed !== t) writeFileSync(join(ROOT, 'packages/shared/test/dzmsd.test.ts'), fixed);
}

console.log('\nRegenerating golden vectors (pnpm vectors)…');
execSync('pnpm vectors', { stdio: 'inherit' });
console.log('\nRunning pnpm check (TypeScript tests + typecheck + independent Python cross-check)…');
try {
  execSync('pnpm check', { stdio: 'inherit' });
  console.log(`\nOK. Review \`git diff\` (especially test-vectors/), then commit: "feat(shared): rename wire magic ${OLD} -> ${NEW}".`);
} catch {
  console.error('\npnpm check FAILED. Do not commit. Read the first failure; most likely a literal packet the regex did not match (look for the old CRC).');
  process.exit(1);
}

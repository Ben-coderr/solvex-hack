// Generates supabase/seed.sql from data/hospitals.seed.json (synthetic demo set, source 'illustrative') and
// data/hospitals.national.json (unverified national set, source 'osm-unverified'; built by scripts/import-hospitals.mjs).
// Postgres seed files cannot read JSON from disk. HOSPITAL_SET picks which set the app ranks.
// Run: pnpm db:seed-sql   — commit both files together.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const VOCAB = new Set(['ed24', 'trauma_surgery', 'ct', 'icu', 'neurosurgery', 'pediatrics', 'burns', 'general_surgery']);
const STATUSES = new Set(['OK', 'BUSY', 'SATURATED']);
const { hospitals: demo, statuses } = JSON.parse(readFileSync('data/hospitals.seed.json', 'utf8'));
const { hospitals: national } = existsSync('data/hospitals.national.json')
  ? JSON.parse(readFileSync('data/hospitals.national.json', 'utf8'))
  : { hospitals: [] };
const SETS = [
  { rows: demo, source: 'illustrative', suffix: /\(illustrative\)$/ },
  { rows: national, source: 'osm-unverified', suffix: /\(unverified\)$/ },
];

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replaceAll("'", "''")}'`);
const fail = (msg) => {
  console.error(`gen-seed-sql: ${msg}`);
  process.exit(1);
};

const ids = new Set();
const rows = SETS.flatMap(({ rows: set, source, suffix }) => set.map((h) => {
  if (ids.has(h.id)) fail(`duplicate id ${h.id}`);
  ids.add(h.id);
  if (!suffix.test(h.name)) fail(`${h.id}: name must end with "(${suffix.source.slice(2, -3)})" until verified`);
  if (source !== 'illustrative' && h.phone_sms) fail(`${h.id}: no phone numbers outside the synthetic set (pre-alerts are texted to them)`);
  if (!['A', 'B', 'C'].includes(h.level)) fail(`${h.id}: bad level ${h.level}`);
  for (const c of h.capabilities) if (!VOCAB.has(c)) fail(`${h.id}: capability "${c}" not in the fixed vocabulary`);
  if (!(Math.abs(h.lat) <= 90 && Math.abs(h.lon) <= 180)) fail(`${h.id}: bad coordinates`);
  const caps = `array[${h.capabilities.map(q).join(',')}]::text[]`;
  return `  (${q(h.id)}, ${q(h.name)}, ${q(h.level)}, ${h.wilaya_code ?? 'null'}, ${q(h.phone_sms)}, ${caps}, ` +
    `extensions.st_setsrid(extensions.st_makepoint(${h.lon}, ${h.lat}), 4326)::extensions.geography, ${q(source)}, false)`;
}));

const statusRows = (statuses ?? []).map((s) => {
  if (!ids.has(s.hospital_id)) fail(`status for unknown hospital ${s.hospital_id}`);
  if (!STATUSES.has(s.status)) fail(`bad status ${s.status}`);
  return `  (${q(s.hospital_id)}, ${q(s.status)}, ${q(s.set_by ?? 'seed')})`;
});

const sql = `-- GENERATED by scripts/gen-seed-sql.mjs from data/hospitals.seed.json + data/hospitals.national.json — do not edit by hand.
-- 'illustrative' = synthetic demo set; 'osm-unverified' = national set, positions from OpenStreetMap, levels and
-- capabilities inferred, no phone numbers. Nothing here is verified (verified = false).

insert into public.hospitals (id, name, level, wilaya_code, phone_sms, capabilities, location, source, verified) values
${rows.join(',\n')};
${statusRows.length ? `
insert into public.hospital_status (hospital_id, status, set_by) values
${statusRows.join(',\n')};
` : ''}`;

writeFileSync('supabase/seed.sql', sql);
console.log(`supabase/seed.sql: ${demo.length} demo + ${national.length} national hospitals, ${statusRows.length} statuses`);

// Generates supabase/seed.sql from data/hospitals.seed.json (Postgres seed files cannot read JSON from disk).
// Run: pnpm db:seed-sql   — commit both files together.
import { readFileSync, writeFileSync } from 'node:fs';

const VOCAB = new Set(['ed24', 'trauma_surgery', 'ct', 'icu', 'neurosurgery', 'pediatrics', 'burns', 'general_surgery']);
const STATUSES = new Set(['OK', 'BUSY', 'SATURATED']);
const { hospitals, statuses } = JSON.parse(readFileSync('data/hospitals.seed.json', 'utf8'));

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replaceAll("'", "''")}'`);
const fail = (msg) => {
  console.error(`gen-seed-sql: ${msg}`);
  process.exit(1);
};

const ids = new Set();
const rows = hospitals.map((h) => {
  if (ids.has(h.id)) fail(`duplicate id ${h.id}`);
  ids.add(h.id);
  if (!/\(illustrative\)$/.test(h.name)) fail(`${h.id}: name must end with "(illustrative)" until verified`);
  if (!['A', 'B', 'C'].includes(h.level)) fail(`${h.id}: bad level ${h.level}`);
  for (const c of h.capabilities) if (!VOCAB.has(c)) fail(`${h.id}: capability "${c}" not in the fixed vocabulary`);
  if (!(Math.abs(h.lat) <= 90 && Math.abs(h.lon) <= 180)) fail(`${h.id}: bad coordinates`);
  const caps = `array[${h.capabilities.map(q).join(',')}]::text[]`;
  return `  (${q(h.id)}, ${q(h.name)}, ${q(h.level)}, ${h.wilaya_code ?? 'null'}, ${q(h.phone_sms)}, ${caps}, ` +
    `extensions.st_setsrid(extensions.st_makepoint(${h.lon}, ${h.lat}), 4326)::extensions.geography, 'illustrative', false)`;
});

const statusRows = (statuses ?? []).map((s) => {
  if (!ids.has(s.hospital_id)) fail(`status for unknown hospital ${s.hospital_id}`);
  if (!STATUSES.has(s.status)) fail(`bad status ${s.status}`);
  return `  (${q(s.hospital_id)}, ${q(s.status)}, ${q(s.set_by ?? 'seed')})`;
});

const sql = `-- GENERATED by scripts/gen-seed-sql.mjs from data/hospitals.seed.json — do not edit by hand.
-- Synthetic, illustrative facilities only (verified = false).

insert into public.hospitals (id, name, level, wilaya_code, phone_sms, capabilities, location, source, verified) values
${rows.join(',\n')};
${statusRows.length ? `
insert into public.hospital_status (hospital_id, status, set_by) values
${statusRows.join(',\n')};
` : ''}`;

writeFileSync('supabase/seed.sql', sql);
console.log(`supabase/seed.sql: ${rows.length} hospitals, ${statusRows.length} statuses`);

#!/usr/bin/env node
// Builds data/hospitals.national.json from a national facility list (e.g. hospitals.algeria_full.json, 773 rows).
//
//   node scripts/import-hospitals.mjs <path/to/list.json>        # writes data/hospitals.national.json, prints what it kept
//   pnpm db:seed-sql                                             # then regenerate supabase/seed.sql
//
// The positions come from OpenStreetMap and look right; the medical fields do NOT: every row, dispensaries and a
// psychiatric hospital included, claimed a 24 h ED + general surgery + CT. So, on purpose:
//   - keep only acute general hospitals (CHU / EHU / EPH / "Hôpital" / مستشفى); drop clinics, care rooms, maternity,
//     paediatric, psychiatric, military, transfusion, dialysis, cancer and other single-specialty centres, except the
//     burns / neurosurgery / trauma EHS (real crash destinations)
//   - level and capabilities come from the TYPE, conservatively: CHU/EHU and those EHS = level A with the list's
//     capabilities (its curated rows); any other hospital = level B with ed24 + general_surgery only
//   - NO phone numbers: they are real hospital lines and the app texts pre-alerts to `phone_sms`
//   - names end with "(unverified)", source 'osm-unverified', verified = false
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/import-hospitals.mjs <list.json>');
  process.exit(1);
}

const VOCAB = new Set(['ed24', 'trauma_surgery', 'ct', 'icu', 'neurosurgery', 'pediatrics', 'burns', 'general_surgery']);
const ACUTE = /\b(chu|ehu|eph|h[oô]pital|hospital)\b|مستشفى/i;
/** single-specialty centres that ARE crash destinations: burns, neurosurgery, trauma (kept with the list's capabilities) */
const REFERRAL = /\behs\b.*(br[uû]l|neurochir|trauma)/i;
const TEACHING = /\b(chu|ehu)\b|universitaire|الجامعي/i;
const EXCLUDE = /psychiatr|transfusion|dialys|tafsiya|تصفية|cancer|anti-?cancer|\bcac\b|ophtalm|r[ée][ée]ducation|p[ée]diatri|matern|obst[ée]tri|gyn[ée]co|m[eè]re et (de l')?enfant|militaire|police|s[uû]ret[ée]|gendarmerie|douane|protection civile|clinique|polyclinique|dispensaire|salle de soin|centre|\bamg\b|\bepsp\b|مركز|عيادة|أمومة|ولادة|عسكري/i;
const ALGERIA = { lat: [18.9, 37.2], lon: [-8.7, 12.0] };

const { hospitals: rows } = JSON.parse(readFileSync(src, 'utf8'));
const kept = [];
const dropped = { type: 0, name: 0, position: 0 };

for (const r of rows) {
  const name = String(r.name ?? '').trim();
  // a bare "EPH" / "Hôpital" says nothing about which one: unusable on a dispatcher card
  if (name.replace(/[^\p{L}]/gu, '').length < 8) { dropped.name++; continue; }
  const referral = r.level === 'A' && REFERRAL.test(name);
  if (!referral && (!ACUTE.test(name) || EXCLUDE.test(name))) { dropped.type++; continue; }
  if (!(r.lat >= ALGERIA.lat[0] && r.lat <= ALGERIA.lat[1] && r.lon >= ALGERIA.lon[0] && r.lon <= ALGERIA.lon[1])) { dropped.position++; continue; }
  const teaching = referral || (r.level === 'A' && TEACHING.test(name));
  kept.push({
    id: `N-${r.id}`.slice(0, 40),
    name: `${name} (unverified)`,
    level: teaching ? 'A' : 'B',
    wilaya_code: r.wilaya_code ?? null,
    lat: Math.round(r.lat * 1e5) / 1e5,
    lon: Math.round(r.lon * 1e5) / 1e5,
    capabilities: teaching ? r.capabilities.filter((c) => VOCAB.has(c)) : ['ed24', 'general_surgery'],
  });
}

const ids = new Set();
for (const h of kept) {
  if (ids.has(h.id)) throw new Error(`duplicate id ${h.id}`);
  ids.add(h.id);
}
kept.sort((a, b) => (a.wilaya_code ?? 99) - (b.wilaya_code ?? 99) || a.id.localeCompare(b.id));

const out = {
  $comment:
    'GENERATED by scripts/import-hospitals.mjs — do not edit by hand. Acute general hospitals from a national list ' +
    'geocoded from OpenStreetMap. Positions plausible, NOTHING verified: level and capabilities are inferred from the ' +
    'facility type (CHU/EHU and burns/neurosurgery EHS = A, other hospitals = B with ED + general surgery only). No phone numbers on purpose. ' +
    'Used only when HOSPITAL_SET=national; the stage demo uses data/hospitals.seed.json.',
  hospitals: kept,
};
writeFileSync('data/hospitals.national.json', `${JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{')}\n`);

const byLevel = kept.reduce((m, h) => ({ ...m, [h.level]: (m[h.level] ?? 0) + 1 }), {});
console.log(`data/hospitals.national.json: kept ${kept.length} of ${rows.length} (A ${byLevel.A ?? 0}, B ${byLevel.B ?? 0}), ` +
  `${new Set(kept.map((h) => h.wilaya_code)).size} wilayas; dropped ${dropped.type} by type, ${dropped.name} unnamed, ${dropped.position} outside Algeria`);
